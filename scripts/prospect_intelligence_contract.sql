CREATE TRIGGER lead_feedback_scope_guard
    BEFORE INSERT OR UPDATE ON public.lead_feedback
    FOR EACH ROW EXECUTE FUNCTION public.guard_lead_feedback_tenant_scope();

DROP TRIGGER IF EXISTS lead_feedback_updated_at ON public.lead_feedback;
CREATE TRIGGER lead_feedback_updated_at
    BEFORE UPDATE ON public.lead_feedback
    FOR EACH ROW EXECUTE FUNCTION public.set_prospect_intelligence_updated_at();

-- Direct database/service roles write discovery telemetry.  Authenticated
-- browser users can only read rows in their workspace and add feedback for a
-- lead match in that workspace; they cannot create, edit, or remove runs.
ALTER TABLE public.discovery_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.discovery_run_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lead_feedback ENABLE ROW LEVEL SECURITY;

