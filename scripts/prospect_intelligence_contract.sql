    FOR SELECT TO authenticated
    USING (
        EXISTS (
            SELECT 1
              FROM public.tenant_users AS tenant_user
             WHERE tenant_user.tenant_id::TEXT = lead_feedback.tenant_id::TEXT
               AND tenant_user.user_id::TEXT = auth.uid()::TEXT
        )
    );

DROP POLICY IF EXISTS lead_feedback_insert_tenant ON public.lead_feedback;
CREATE POLICY lead_feedback_insert_tenant ON public.lead_feedback
    FOR INSERT TO authenticated
    WITH CHECK (
        EXISTS (
            SELECT 1
              FROM public.tenant_users AS tenant_user
             WHERE tenant_user.tenant_id::TEXT = lead_feedback.tenant_id::TEXT
               AND tenant_user.user_id::TEXT = auth.uid()::TEXT
        )
        AND lead_feedback.user_id::TEXT = auth.uid()::TEXT
        AND EXISTS (
            SELECT 1
              FROM public.lead_matches AS lead_match
             WHERE lead_match.id = lead_feedback.lead_match_id
               AND lead_match.tenant_id::TEXT = lead_feedback.tenant_id::TEXT
        )
    );

